#!/usr/bin/env bash
#
# Compiles the app's Kotlin without Gradle, the Android SDK or an emulator.
#
# The Kotlin is three files' worth of edge-to-edge setup and a verification
# channel. When it does not compile, the failure shows up in a GitHub Actions
# run seven minutes later, after a full Flutter build and a Gradle
# configuration - and the same run three times over, because the workflow
# retries the APK build. Two Kotlin mistakes were found that way.
#
# This script catches them in seconds instead.
#
# It needs:
#
#   * a Kotlin compiler (2.4.0, the version the project builds with)
#   * the Flutter embedding jar for the engine the project pins
#   * android.jar from the platform SDK
#   * the AndroidX jars the Flutter embedding needs: lifecycle-common-jvm,
#     lifecycle-runtime-android, core and annotation
#
# The paths can be given as arguments, or found from the environment:
#
#   KOTLINC        the kotlinc script
#   FLUTTER_ROOT   the Flutter SDK
#   ANDROID_JAR    an android.jar
#   ANDROIDX_DIR   a directory holding the AndroidX jars
#
# A missing dependency is reported and the check is skipped - it is a
# fast check, not a gate. The Actions build remains the authority.

set -uo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
KOTLIN_SRC="$REPO_ROOT/android/app/src/main/kotlin"

KOTLINC="${KOTLINC:-$HOME/kotlin/kotlinc/bin/kotlinc}"
FLUTTER_ROOT="${FLUTTER_ROOT:-$HOME/sdk/flutter}"
ANDROID_JAR="${ANDROID_JAR:-$HOME/android35/android-35/android.jar}"
ANDROIDX_DIR="${ANDROIDX_DIR:-$HOME/androidx}"

skip() {
  echo "skip: $1"
  exit 0
}

[ -x "$KOTLINC" ] || skip "no Kotlin compiler at $KOTLINC"
[ -f "$ANDROID_JAR" ] || skip "no android.jar at $ANDROID_JAR"
[ -d "$ANDROIDX_DIR" ] || skip "no AndroidX directory at $ANDROIDX_DIR"

# The Flutter embedding jar is named after the engine revision the SDK
# pins, so the jar always matches the Flutter the project builds with.
EMBEDDING_JAR="$HOME/flutter-embedding.jar"
if [ ! -f "$EMBEDDING_JAR" ]; then
  ENGINE_REV="$(cat "$FLUTTER_ROOT/bin/internal/engine.version" 2>/dev/null || true)"
  if [ -n "$ENGINE_REV" ]; then
    echo "fetching the Flutter embedding jar for engine $ENGINE_REV"
    curl -sL -o "$EMBEDDING_JAR" \
      "https://storage.googleapis.com/download.flutter.io/io/flutter/flutter_embedding_debug/1.0.0-$ENGINE_REV/flutter_embedding_debug-1.0.0-$ENGINE_REV.jar" || true
  fi
fi
[ -f "$EMBEDDING_JAR" ] || skip "no Flutter embedding jar"

# BuildConfig is generated by Gradle, so it is stubbed here. Only the
# DEBUG flag matters to the Kotlin.
STUB_DIR="$(mktemp -d)"
trap 'rm -rf "$STUB_DIR"' EXIT
mkdir -p "$STUB_DIR/com/mahimmazidul/elara"
cat > "$STUB_DIR/com/mahimmazidul/elara/BuildConfig.java" <<'EOF'
package com.mahimmazidul.elara;
public final class BuildConfig {
    public static final boolean DEBUG = true;
}
EOF
javac -d "$STUB_DIR" "$STUB_DIR/com/mahimmazidul/elara/BuildConfig.java" \
  || skip "no javac to build the BuildConfig stub"

CP="$STUB_DIR"
CP="$CP:$EMBEDDING_JAR"
CP="$CP:$ANDROID_JAR"
for jar in \
  "$ANDROIDX_DIR/lifecycle-common-jvm-2.9.4.jar" \
  "$ANDROIDX_DIR/x-lra/classes.jar" \
  "$ANDROIDX_DIR/core-1.15.0-classes.jar" \
  "$ANDROIDX_DIR/annotation-1.9.1.jar"; do
  [ -f "$jar" ] || skip "missing AndroidX jar $jar"
  CP="$CP:$jar"
done

SOURCES="$(find "$KOTLIN_SRC" -name '*.kt' | sort)"
[ -n "$SOURCES" ] || skip "no Kotlin sources under $KOTLIN_SRC"

echo "compiling $(echo "$SOURCES" | wc -l) Kotlin file(s) with $("$KOTLINC" -version 2>&1 | head -1)"

# Deprecation warnings are expected: the edge-to-edge code deliberately uses
# the deprecated window flags on older API levels, and says why. Only errors
# fail the check.
output="$("$KOTLINC" -classpath "$CP" -d "$STUB_DIR/out.jar" $SOURCES 2>&1)"
status=$?

errors="$(echo "$output" | grep -E "error:" || true)"
if [ -n "$errors" ]; then
  echo "$errors"
  echo "FAIL: the Kotlin does not compile."
  exit 1
fi

if [ $status -ne 0 ]; then
  echo "$output"
  echo "FAIL: the Kotlin compiler exited $status."
  exit 1
fi

warnings="$(echo "$output" | grep -c "^.*warning:" || true)"
echo "OK: the Kotlin compiles ($warnings warning(s), no errors)."
